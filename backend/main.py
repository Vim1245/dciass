@app.post("/chat")
async def chat(request: ChatRequest):
    if not request.message or not request.message.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )
    try:
        response = await generate_response(
            message=request.message,
            context=request.context
        )
        return {
            "message": request.message,
            "response": response
        }
    except Exception:
        return {
            "message": request.message,
            "response": "An error occurred while processing the chat request. Please try again."
        }


@app.post("/agent")
async def agent_chat(request: ChatRequest):
    if not request.message or not request.message.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )
    try:
        response = await run_customer_agent(
            request.message
        )
        return {
            "message": request.message,
            "response": response
        }
    except Exception:
        return {
            "message": request.message,
            "response": "An error occurred while executing the customer agent."
        }


@app.post("/workflow")
async def workflow_chat(request: ChatRequest):
    """
    Complete Agentic AI Business Support Workflow endpoint:
    Understands request, plans actions, retrieves info via MCP/RAG,
    analyzes via configured provider (Gemini/Ollama), generates business decision, and executes MCP actions.
    """
    if not request.message or not request.message.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )

    try:
        result = await business_graph.ainvoke({
            "question": request.message.strip(),
            "category": "",
            "customer_name": "",
            "customer_names": [],
            "required_actions": [],
            "customer_data": "",
            "complaint_data": "",
            "policy_context": "",
            "decision": "",
            "ticket_result": "",
            "response": "",
        })

        return {
            "message": request.message,
            "response": result.get("response", ""),
            "decision": result.get("decision", ""),
            "ticket": result.get("ticket_result", ""),
            "category": result.get("category", ""),
            "customer_data": result.get("customer_data", ""),
            "complaint_data": result.get("complaint_data", ""),
            "policy_context": result.get("policy_context", ""),
        }
    except Exception:
        return {
            "message": request.message,
            "response": "An error occurred while executing the business workflow. Please check your configuration and try again.",
            "decision": "MORE_INFORMATION_REQUIRED",
            "ticket": "",
            "category": "error",
            "customer_data": "",
            "complaint_data": "",
            "policy_context": "",
        }


@app.post(
    "/api/assistant",
    response_model=AssistantResponse,
    response_model_exclude_none=True,
    summary="Agentic AI Business Assistant Gateway",
    description="Processes natural-language business requests through LangGraph, MCP tools, ChromaDB RAG, and Ollama reasoning."
)
async def assistant_endpoint(request: AssistantRequest):
    """
    Dedicated Business Assistant Endpoint (STEP 10.4):
    Routes through LangGraph with Ollama, MCP tools, and RAG policy context.
    Returns clean response, business decision, and ticket result without exposing internal state.
    """
    cleaned_message = request.message.strip()
    if not cleaned_message:
        logger.warning("Assistant request rejected: empty message")
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )

    if len(cleaned_message) > MAX_MESSAGE_LENGTH:
        logger.warning("Assistant request rejected: message length %d exceeds %d", len(cleaned_message), MAX_MESSAGE_LENGTH)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Message exceeds maximum allowed length of {MAX_MESSAGE_LENGTH} characters."
        )

    logger.info("Assistant request received (length: %d chars)", len(cleaned_message))
    logger.info("Executing LangGraph agentic workflow...")

    try:
        result = await business_graph.ainvoke({
            "question": cleaned_message,
            "category": "",
            "customer_name": "",
            "customer_names": [],
            "required_actions": [],
            "customer_data": "",
            "complaint_data": "",
            "policy_context": "",
            "decision": "",
            "ticket_result": "",
            "response": "",
        })

        decision = result.get("decision", "NO_ACTION")
        if decision not in ("CREATE_TICKET", "MORE_INFORMATION_REQUIRED", "NO_ACTION"):
            logger.warning("Invalid decision '%s' returned. Defaulting to safe fallback.", decision)
            decision = "MORE_INFORMATION_REQUIRED"

        ticket_res = result.get("ticket_result", "").strip() or None
        if ticket_res:
            logger.info("Ticket generated successfully via MCP: %s", ticket_res[:40])

        logger.info("LangGraph workflow completed. Decision: %s", decision)

        return AssistantResponse(
            message=cleaned_message,
            response=result.get("response", ""),
            decision=decision,
            ticket=ticket_res
        )
    except Exception as e:
        logger.error("Error during LangGraph assistant execution: %s", type(e).__name__)
        # Never expose stack traces, keys, or internal paths
        return AssistantResponse(
            message=cleaned_message,
            response="A system error occurred while processing your request. Please ensure the backend and AI services are running.",
            decision="MORE_INFORMATION_REQUIRED",
            ticket=None
        )


