MAX_MESSAGE_LENGTH = 10000


class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=MAX_MESSAGE_LENGTH, description="User message or business request")
    context: str = Field(default="", description="Optional additional context")


class AssistantRequest(BaseModel):
    message: str = Field(
        ...,
        min_length=1,
        max_length=MAX_MESSAGE_LENGTH,
        description="Natural language business request or query for the assistant."
    )


class AssistantResponse(BaseModel):
    message: str = Field(..., description="The original user query processed by the assistant.")
    response: str = Field(..., description="The final business response generated by the agentic workflow.")
    decision: str = Field(..., description="Business decision: CREATE_TICKET, MORE_INFORMATION_REQUIRED, or NO_ACTION.")
    ticket: Optional[str] = Field(default=None, description="Support ticket details if created, otherwise omitted.")


